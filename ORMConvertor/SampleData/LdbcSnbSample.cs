    /// <summary>
    /// A count over the whole result, which LINQ says only by ending the chain in the call,
    /// and no other chain returns the same rows - so EF Core writes it in native SQL
    /// (decision 113).
    /// </summary>
    private static readonly LdbcFallback EFCoreCount = new(Model.ORMEnum.EFCore,
        "A count over the whole result is a call that ends a LINQ chain, not a query, so the query goes out as native SQL through SqlQuery.");

    /// <summary>
    /// A query over the result of another query - a common table expression, a derived table -
    /// has no form in two of the six query languages (decision 112), and those two targets
    /// write it in native SQL (decision 113).
    /// </summary>
    private static readonly LdbcFallback NHibernateIntermediate = new(Model.ORMEnum.NHibernate,
        "HQL of NHibernate 5.7 has neither WITH nor a subquery in FROM, so the query goes out as native SQL through CreateSQLQuery.");

    private static readonly LdbcFallback EclipseLinkIntermediate = new(Model.ORMEnum.EclipseLink,
        "JPQL has neither WITH nor a subquery in FROM - EclipseLink's own subquery in FROM stands only as a cross join beside an entity -, so the query goes out as native SQL through createNativeQuery.");

    /// <summary>
    /// A recursive definition (decision 113) has no form in three of the six query languages:
    /// LINQ writes a definition as a variable, which cannot name itself, and HQL of NHibernate
    /// and JPQL have no definition at all. Those three targets write it in native SQL; HQL of
    /// Hibernate 7.4 and T-SQL write it in their own language.
    /// </summary>
    private static readonly LdbcFallback EFCoreRecursion = new(Model.ORMEnum.EFCore,
        "LINQ has no recursion - a definition is a variable of the method, and a variable cannot name itself -, so the query goes out as native SQL through SqlQuery.");

    private static readonly LdbcFallback NHibernateRecursion = new(Model.ORMEnum.NHibernate,
        "HQL of NHibernate 5.7 has no WITH, let alone one that names itself, so the query goes out as native SQL through CreateSQLQuery.");

    private static readonly LdbcFallback EclipseLinkRecursion = new(Model.ORMEnum.EclipseLink,
        "JPQL has no WITH, let alone one that names itself, so the query goes out as native SQL through createNativeQuery.");

    /// <summary>
    /// Date arithmetic - DATEADD and DATEDIFF - has no form in HQL of NHibernate 5.7 nor in
    /// JPQL (decision 113, measured against NHibernate 5.7.0): those two targets write the query
    /// in native SQL. LINQ calls the Add methods and EF.Functions.DateDiff…, HQL of Hibernate
    /// timestampadd and timestampdiff.
    /// </summary>
    private static readonly LdbcFallback NHibernateDates = new(Model.ORMEnum.NHibernate,
        "HQL of NHibernate 5.7 has no date arithmetic - neither dateadd nor datediff -, so the query goes out as native SQL through CreateSQLQuery.");

    private static readonly LdbcFallback EclipseLinkDates = new(Model.ORMEnum.EclipseLink,
        "JPQL has no date arithmetic, so the query goes out as native SQL through createNativeQuery.");

    /// <summary>
    /// A list joined from the values of a group - STRING_AGG - has no form in HQL of NHibernate
    /// 5.7 nor in JPQL (decision 113, measured): those targets write the query in native SQL.
    /// EF Core writes a list over a correlated subquery as the chain grouped by a constant.
    /// </summary>
    private static readonly LdbcFallback NHibernateList = new(Model.ORMEnum.NHibernate,
        "HQL of NHibernate 5.7 has no aggregate into a list, so the query goes out as native SQL through CreateSQLQuery.");

    private static readonly LdbcFallback EclipseLinkList = new(Model.ORMEnum.EclipseLink,
        "JPQL has no aggregate into a list, so the query goes out as native SQL through createNativeQuery.");

    /// <summary>
    /// A ranking function over a window has no form in LINQ (decision 113): EF Core writes the
    /// query in native SQL.
    /// </summary>
    private static readonly LdbcFallback EFCoreWindow = new(Model.ORMEnum.EFCore,
        "LINQ has no ranking function over a window, so the query goes out as native SQL through SqlQuery.");

    /// <summary>
    /// EclipseLink 5.0 passes the type name of a JPQL cast through to SQL Server, which knows no
    /// type Integer, Long or String and refuses the query (decision 113, measured), so a
    /// conversion sends the query to native SQL - its descriptor leaves Cast out.
    /// </summary>
    private static readonly LdbcFallback EclipseLinkCast = new(Model.ORMEnum.EclipseLink,
        "JPQL of EclipseLink 5.0 passes the type name of a conversion through to SQL Server, which knows no type Long, so the query goes out as native SQL through createNativeQuery.");

    /// <summary>
    /// HQL of Hibernate 7.4 converts into String as varchar(max), which would lose the
    /// characters of a text no code page holds (decision 113, measured); a conversion of a text
    /// therefore sends the query to native SQL.
    /// </summary>
    private static readonly LdbcFallback HibernateTextCast = new(Model.ORMEnum.Hibernate,
        "HQL of Hibernate 7.4 converts a text into varchar(max), which would lose characters a tag name may hold, so the query goes out as native SQL through createNativeQuery.");

    /// <summary>
    /// An outer join whose condition names an inner join: EclipseLink 5.0 writes the inner joins
